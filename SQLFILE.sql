#6. CANCELLATION % #

SELECT SUM(IF(BOOKING_STATUS = "CANCELLED",1,0)) AS "CANCELLATION COUNT",
CONCAT((SUM(IF(BOOKING_STATUS = "CANCELLED",1,0))/COUNT(BOOKING_ID))*100,"%") AS "CANCELLATION %"  FROM FACT_BOOKINGS;

#7. CHECKED OUT % #

SELECT SUM(IF(BOOKING_STATUS = "CHECKED OUT",1,0)) AS "CHECKED OUT COUNT",
CONCAT((SUM(IF(BOOKING_STATUS = "CHECKED OUT",1,0))/COUNT(BOOKING_ID))*100,"%") AS "CHECKED OUT %"  FROM FACT_BOOKINGS;

#8. NO SHOW % #

SELECT SUM(IF(BOOKING_STATUS = "NO SHOW",1,0)) AS "NO SHOW COUNT",
