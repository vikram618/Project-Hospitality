#35. REVENUE PER AVAILABLE ROOM

SELECT 
    SUM(b.revenue_generated) / SUM(a.capacity) AS "REVENUE PER AVAILABLE ROOM"
FROM
    (SELECT room_category, SUM(revenue_generated) AS revenue_generated
     FROM fact_bookings
     GROUP BY room_category) b
JOIN
    (SELECT room_category, SUM(capacity) AS capacity
     FROM fact_aggregated_bookings
     GROUP BY room_category) a
ON b.room_category = a.room_category;


